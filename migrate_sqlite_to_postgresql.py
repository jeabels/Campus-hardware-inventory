"""
migrate_sqlite_to_postgresql.py - Lab 8, Part D

Copies the Campus Hardware Inventory tables from the local SQLite database
(models/hardware_inventory.db) into the Supabase PostgreSQL database.

Tables used by THIS system (Lab 8 note: "This will depend on the tables you have created"):
    users, inventory, borrow_log, password_reset_requests, system_logs, app_settings

Run once, BEFORE starting app.py against Supabase:
    set "DATABASE_URL=YOUR_SUPABASE_CONNECTION_STRING"
    python migrate_sqlite_to_postgresql.py
"""

import os  # Provides access to operating-system environment variables and file paths.
import sqlite3  # Provides SQLite database access for the original local database.

import psycopg  # Provides PostgreSQL database access.
from psycopg import sql  # Provides safe SQL construction for table and column identifiers.

BASE_DIR = os.path.dirname(os.path.abspath(__file__))  # Folder that contains this script.
SQLITE_CANDIDATES = [  # Places where the desktop app may have saved the SQLite database.
    os.getenv("SQLITE_DB", ""),  # Optional custom path supplied through an environment variable.
    os.path.join(BASE_DIR, "models", "hardware_inventory.db"),  # Default path used by Laboratorysystem.py.
    os.path.join(BASE_DIR, "hardware_inventory.db"),  # Path used in the lab handout example.
]  # Ends the candidate list.
SQLITE_DB = next((p for p in SQLITE_CANDIDATES if p and os.path.exists(p)), None)  # Picks the first file that exists.
if SQLITE_DB is None:  # Checks whether the SQLite database was found.
    raise RuntimeError("hardware_inventory.db was not found (looked in models/ and the project folder).")  # Stops early.

DATABASE_URL = os.getenv("DATABASE_URL")  # Reads the PostgreSQL connection string from the environment.
if not DATABASE_URL:  # Checks whether the PostgreSQL connection string was provided.
    raise RuntimeError("DATABASE_URL is not set.")  # Stops the migration if the connection string is missing.
if not DATABASE_URL.startswith(("postgresql://", "postgres://")):  # Checks for a placeholder or malformed value.
    raise RuntimeError("DATABASE_URL must be the full Supabase URI that starts with postgresql://")  # Stops early.

print(f"Source SQLite file: {os.path.relpath(SQLITE_DB, BASE_DIR)}")  # Shows which SQLite file will be copied.

sqlite_conn = sqlite3.connect(SQLITE_DB)  # Opens the original SQLite database.
sqlite_conn.row_factory = sqlite3.Row  # Allows SQLite rows to be accessed by column name.
pg_conn = psycopg.connect(DATABASE_URL, prepare_threshold=None)  # Opens Supabase PostgreSQL (pooler-safe).
pg_conn.autocommit = False  # Uses a transaction so changes can be rolled back if an error occurs.

try:  # Starts the protected migration section.
    pg_cur = pg_conn.cursor()  # Creates a PostgreSQL cursor for SQL commands.
    sqlite_cur = sqlite_conn.cursor()  # Creates a SQLite cursor for reading source data.

    table_definitions = {  # Defines the PostgreSQL tables required by this application (parents first).
        "users": [  # Defines the users table.
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",  # Creates the user ID column.
            "username TEXT UNIQUE NOT NULL",  # Stores each user's unique username.
            "email TEXT UNIQUE NOT NULL",  # Stores the user's unique email address.
            "password_hash TEXT NOT NULL",  # Stores the bcrypt password hash (never the real password).
            "role TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER'))",  # Restricts the user role.
            "failed_attempts INTEGER NOT NULL DEFAULT 0",  # Stores the number of failed login attempts.
            "is_locked INTEGER NOT NULL DEFAULT 0",  # Stores whether the account is locked (1) or not (0).
            "is_active INTEGER NOT NULL DEFAULT 1",  # Stores whether the account is enabled (1) or disabled (0).
            "created_at TEXT NOT NULL DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')",  # Stores when it was created.
        ],  # Ends the users column definition list.
        "inventory": [  # Defines the hardware inventory table.
            "item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",  # Creates the hardware item ID.
            "item_name TEXT UNIQUE NOT NULL",  # Stores the hardware item name.
            "category TEXT NOT NULL",  # Stores the hardware category.
            "stock INTEGER NOT NULL DEFAULT 0",  # Stores the available stock quantity.
            "unit_price DOUBLE PRECISION NOT NULL DEFAULT 0",  # Stores the price of one unit.
            "in_stock TEXT NOT NULL DEFAULT 'Out of Stock'",  # Stores the calculated stock status label.
        ],  # Ends the inventory column definition list.
        "borrow_log": [  # Defines the borrowing and return table.
            "log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",  # Creates the loan record ID.
            "item_id BIGINT NOT NULL REFERENCES inventory(item_id)",  # Stores the borrowed hardware ID.
            "item_name TEXT NOT NULL",  # Stores the hardware name at the time of borrowing.
            "borrower_name TEXT NOT NULL",  # Stores the student's name.
            "school_id TEXT NOT NULL DEFAULT ''",  # Stores the student's school ID.
            "quantity INTEGER NOT NULL DEFAULT 1",  # Stores how many units were borrowed.
            "processed_by TEXT NOT NULL DEFAULT ''",  # Stores the staff/admin who processed the loan.
            "borrow_date TEXT NOT NULL",  # Stores the borrow request/borrow date.
            "due_date TEXT",  # Stores the due date.
            "return_date TEXT",  # Stores the return date when available.
            "status TEXT NOT NULL DEFAULT 'BORROWED' CHECK (status IN "
            "('PENDING_BORROW', 'BORROWED', 'RETURN_PENDING', 'RETURNED', 'REJECTED'))",  # Restricts loan statuses.
            "notes TEXT",  # Stores optional notes.
            "requested_by TEXT NOT NULL DEFAULT ''",  # Stores the account that submitted the request.
        ],  # Ends the borrow_log column definition list.
        "password_reset_requests": [  # Defines the password reset request table.
            "request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",  # Creates the reset request ID.
            "user_id BIGINT NOT NULL REFERENCES users(id)",  # Links the request to a user account.
            "username TEXT NOT NULL",  # Stores the username requesting the reset.
            "email TEXT NOT NULL",  # Stores the email used for the request.
            "new_password_hash TEXT NOT NULL",  # Stores the requested new password hash.
            "status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))",  # Restricts status.
            "requested_at TEXT NOT NULL",  # Stores when the request was created.
            "reviewed_at TEXT",  # Stores when an administrator reviewed it.
            "reviewed_by TEXT",  # Stores which administrator reviewed it.
        ],  # Ends the password reset column definition list.
        "system_logs": [  # Defines the audit trail table.
            "log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",  # Creates the audit entry ID.
            "username TEXT",  # Stores who performed the action.
            "action TEXT NOT NULL",  # Stores the action name (LOGIN, BORROW, RETURN, ...).
            "details TEXT",  # Stores a readable description.
            "timestamp TEXT NOT NULL",  # Stores when it happened.
        ],  # Ends the system_logs column definition list.
        "app_settings": [  # Defines the key/value settings table.
            "key TEXT PRIMARY KEY",  # Stores the setting name.
            "value TEXT NOT NULL",  # Stores the setting value.
        ],  # Ends the app_settings column definition list.
    }  # Ends the table definition dictionary.

    for table_name, columns in table_definitions.items():  # Processes each required application table.
        column_sql = sql.SQL(", ").join(sql.SQL(column) for column in columns)  # Safely combines column definitions.
        create_sql = sql.SQL("CREATE TABLE IF NOT EXISTS {} ({})").format(sql.Identifier(table_name), column_sql)  # Builds CREATE TABLE.
        pg_cur.execute(create_sql)  # Creates the table if it does not already exist.

    index_statements = [  # Case-insensitive unique names (SQLite used COLLATE NOCASE) and search indexes.
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username_lower ON users (LOWER(username))",  # One username per spelling.
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower ON users (LOWER(email))",  # One account per email.
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_inventory_name_lower ON inventory (LOWER(item_name))",  # No duplicate items.
        "CREATE INDEX IF NOT EXISTS idx_borrow_school_id ON borrow_log (school_id)",  # Faster student look-ups.
        "CREATE INDEX IF NOT EXISTS idx_borrow_status ON borrow_log (status)",  # Faster status filters.
    ]  # Ends the index list.
    for statement in index_statements:  # Processes each index.
        pg_cur.execute(statement)  # Creates the index if it does not already exist.

    counts = {}  # Creates a dictionary for recording migrated row counts.
    for table_name in table_definitions:  # Processes each table for data migration (parents before children).
        pg_cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table_name)))  # Counts existing rows.
        destination_count = pg_cur.fetchone()[0]  # Reads the number of existing rows.
        if destination_count > 0:  # Checks whether the destination table is already populated.
            raise RuntimeError(  # Stops to prevent accidental duplicate migration.
                f"Destination table '{table_name}' is not empty. If app.py already ran against Supabase, "
                "drop the tables in the Supabase SQL Editor and run this script again."
            )  # Ends the error message.

        sqlite_cur.execute("SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?", (table_name,))  # Looks for the table.
        if sqlite_cur.fetchone() is None:  # Checks whether an older SQLite file lacks this table.
            counts[table_name] = 0  # Records zero rows for a missing source table.
            continue  # Moves to the next table.

        quoted_table = '"' + table_name.replace('"', '""') + '"'  # SQLite needs a plain string, not a psycopg sql object.
        sqlite_cur.execute(f"SELECT * FROM {quoted_table}")  # Reads all rows from the matching SQLite table.
        rows = sqlite_cur.fetchall()  # Stores the source rows in memory.
        counts[table_name] = len(rows)  # Records how many rows will be migrated.
        if not rows:  # Checks whether the source table has no rows.
            continue  # Moves to the next table when there is nothing to copy.

        source_columns = [description[0] for description in sqlite_cur.description]  # Gets the SQLite column names.
        pg_cur.execute(  # Reads the destination column names from PostgreSQL.
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = %s",
            (table_name,),
        )  # Ends the column query.
        destination_columns = {row[0] for row in pg_cur.fetchall()}  # Stores the destination column names.
        # Only copy columns that exist on both sides. A column missing from an older SQLite file
        # (for example borrow_log.school_id or requested_by) receives its PostgreSQL DEFAULT value.
        insert_columns = [column for column in source_columns if column in destination_columns]  # Shared columns.

        column_identifiers = sql.SQL(", ").join(sql.Identifier(column) for column in insert_columns)  # Safe INSERT column list.
        placeholders = sql.SQL(", ").join(sql.Placeholder() for _ in insert_columns)  # One placeholder per value.
        insert_sql = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(  # Builds the INSERT statement.
            sql.Identifier(table_name), column_identifiers, placeholders
        )  # Ends the INSERT construction.
        values = [[row[column] for column in insert_columns] for row in rows]  # Gets every row's values in column order.
        pg_cur.executemany(insert_sql, values)  # Inserts all rows (faster than one network trip per row).

    sequence_columns = {  # Maps each table to its identity ID column.
        "users": "id",  # Identifies the users primary key column.
        "inventory": "item_id",  # Identifies the inventory primary key column.
        "borrow_log": "log_id",  # Identifies the borrow_log primary key column.
        "password_reset_requests": "request_id",  # Identifies the password reset primary key column.
        "system_logs": "log_id",  # Identifies the system_logs primary key column.
    }  # Ends the identity column mapping (app_settings uses a text key, so it has no sequence).
    for table_name, id_column in sequence_columns.items():  # Processes each identity column.
        sequence_sql = sql.SQL(  # Builds SQL to synchronize the identity sequence with the migrated IDs.
            "SELECT setval(pg_get_serial_sequence({}, {}), COALESCE(MAX({}), 1), MAX({}) IS NOT NULL) FROM {}"
        ).format(
            sql.Literal(table_name),  # Supplies the table name as a SQL value.
            sql.Literal(id_column),  # Supplies the ID column name as a SQL value.
            sql.Identifier(id_column),  # Supplies the ID column as an SQL identifier for MAX.
            sql.Identifier(id_column),  # Supplies the ID column again for the sequence state test.
            sql.Identifier(table_name),  # Supplies the table name as an SQL identifier.
        )  # Finishes the sequence SQL construction.
        pg_cur.execute(sequence_sql)  # Updates the identity sequence after explicit IDs were inserted.

    pg_conn.commit()  # Permanently saves all migrated tables and rows.

    print("Migration completed successfully.")  # Reports that the migration finished.
    for table_name in table_definitions:  # Displays one line per table.
        pg_cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table_name)))  # Re-counts in Supabase.
        print(f"  {table_name}: {counts[table_name]} (now in PostgreSQL: {pg_cur.fetchone()[0]})")  # Source vs destination.

except Exception:  # Catches any error during migration.
    pg_conn.rollback()  # Cancels PostgreSQL changes made during the failed transaction.
    raise  # Re-raises the original error so the student can see the problem.
finally:  # Runs cleanup whether migration succeeds or fails.
    sqlite_conn.close()  # Closes the SQLite database connection.
    pg_conn.close()  # Closes the PostgreSQL database connection.
